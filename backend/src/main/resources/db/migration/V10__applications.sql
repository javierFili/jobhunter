-- Phase 6: application tracking (NO e-mail sending: the user sends applications manually and records them here).

CREATE TABLE applications (
    id                     BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id                BIGINT UNSIGNED NOT NULL,
    job_offer_id           BIGINT UNSIGNED NULL,
    company_name           VARCHAR(200)    NOT NULL,
    position_title         VARCHAR(300)    NOT NULL,
    job_url                VARCHAR(1000)   NULL,
    source_label           VARCHAR(100)    NULL,
    status                 VARCHAR(20)     NOT NULL DEFAULT 'DISCOVERED',
    method                 VARCHAR(20)     NULL,
    resume_id              BIGINT UNSIGNED NULL,
    resume_version_no      INT             NULL,
    cover_letter_id        BIGINT UNSIGNED NULL,
    salary_expectation     DECIMAL(12, 2)  NULL,
    salary_currency        CHAR(3)         NULL,
    salary_period          VARCHAR(8)      NULL,
    applied_at             DATETIME(6)     NULL,
    follow_up_at           DATE            NULL,
    follow_up_notified_on  DATE            NULL,
    notes                  TEXT            NULL,
    kanban_order           INT             NOT NULL DEFAULT 0,
    created_at             DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at             DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    deleted_at             DATETIME(6)     NULL,
    version                INT             NOT NULL DEFAULT 0,
    CONSTRAINT fk_app_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_app_offer FOREIGN KEY (job_offer_id) REFERENCES job_offers (id) ON DELETE SET NULL,
    CONSTRAINT fk_app_resume FOREIGN KEY (resume_id) REFERENCES resumes (id) ON DELETE SET NULL,
    CONSTRAINT fk_app_letter FOREIGN KEY (cover_letter_id) REFERENCES cover_letters (id) ON DELETE SET NULL,
    CONSTRAINT ck_app_status CHECK (status IN ('DISCOVERED', 'ANALYZED', 'FAVORITE', 'CV_OPTIMIZED', 'READY_TO_APPLY',
        'APPLIED', 'RESPONSE_RECEIVED', 'INTERVIEW', 'OFFER', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_app_method CHECK (method IS NULL OR method IN ('EMAIL', 'EXTERNAL_FORM', 'CAREER_PORTAL', 'LINKEDIN',
        'FREELANCE_PLATFORM', 'OTHER')),
    INDEX ix_app_user_status (user_id, deleted_at, status, kanban_order),
    INDEX ix_app_user_job (user_id, job_offer_id),
    INDEX ix_app_follow_up (follow_up_at, status)
) ENGINE = InnoDB;

CREATE TABLE application_events (
    id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    application_id  BIGINT UNSIGNED NOT NULL,
    type            VARCHAR(24)     NOT NULL,
    from_status     VARCHAR(20)     NULL,
    to_status       VARCHAR(20)     NULL,
    note            TEXT            NULL,
    payload         JSON            NULL,
    occurred_at     DATETIME(6)     NOT NULL,
    created_by      BIGINT UNSIGNED NULL,
    created_at      DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_ae_app FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE,
    CONSTRAINT ck_ae_type CHECK (type IN ('STATUS_CHANGE', 'NOTE', 'SUBMISSION_CONFIRMED', 'FOLLOW_UP', 'MESSAGE_RECEIVED',
        'INTERVIEW_SCHEDULED', 'DOCUMENT_ATTACHED')),
    INDEX ix_ae_app (application_id, occurred_at)
) ENGINE = InnoDB;
