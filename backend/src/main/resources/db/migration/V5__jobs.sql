-- Phase 3: job sources, normalized/deduplicated job offers, source references, tags, per-user state.

CREATE TABLE job_sources (
    id                     BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    code                   VARCHAR(60)  NOT NULL,
    type                   VARCHAR(24)  NOT NULL,
    display_name           VARCHAR(100) NOT NULL,
    enabled                BOOLEAN      NOT NULL DEFAULT TRUE,
    terms_url              VARCHAR(500) NULL,
    terms_notes            TEXT         NULL,
    attribution_text       VARCHAR(200) NULL,
    attribution_required   BOOLEAN      NOT NULL DEFAULT FALSE,
    commercial_use_allowed BOOLEAN      NOT NULL DEFAULT FALSE,
    min_interval_minutes   INT          NOT NULL DEFAULT 60,
    daily_request_cap      INT          NULL,
    last_fetch_at          DATETIME(6)  NULL,
    created_at             DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at             DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT uk_source_code UNIQUE (code),
    CONSTRAINT ck_source_type CHECK (type IN ('PUBLIC_API', 'ATS_BOARD', 'SEARCH_API', 'APIFY_ACTOR'))
) ENGINE = InnoDB;

