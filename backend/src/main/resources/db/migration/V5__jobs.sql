CREATE TABLE company_watchlist (
    id               BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id          BIGINT UNSIGNED NOT NULL,
    ats              VARCHAR(16)     NOT NULL,
    board_token      VARCHAR(120)    NOT NULL,
    company_name     VARCHAR(200)    NULL,
    enabled          BOOLEAN         NOT NULL DEFAULT TRUE,
    last_checked_at  DATETIME(6)     NULL,
    last_status      VARCHAR(16)     NULL,
    last_job_count   INT             NULL,
    created_at       DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at       DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT uk_watch UNIQUE (user_id, ats, board_token),
    CONSTRAINT fk_watch_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_watch_ats CHECK (ats IN ('GREENHOUSE', 'LEVER', 'ASHBY'))
) ENGINE = InnoDB;

CREATE TABLE job_offers (
    id                     BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    title                  VARCHAR(300)    NOT NULL,
    normalized_title       VARCHAR(300)    NOT NULL,
    company_name           VARCHAR(200)    NULL,
    normalized_company     VARCHAR(200)    NULL,
    description_html       MEDIUMTEXT      NULL,
    description_text       MEDIUMTEXT      NULL,
    location_text          VARCHAR(500)    NULL,
    country                CHAR(2)         NULL,
    region                 VARCHAR(16)     NULL,
    work_modality          VARCHAR(16)     NOT NULL DEFAULT 'UNKNOWN',
    remote_scope           VARCHAR(24)     NOT NULL DEFAULT 'UNKNOWN',
    remote_countries       JSON            NULL,
    bolivia_eligibility    VARCHAR(16)     NOT NULL DEFAULT 'UNKNOWN',
    eligibility_evidence   VARCHAR(1000)   NULL,
    engagement_type        VARCHAR(24)     NOT NULL DEFAULT 'UNKNOWN',
    contract_type          VARCHAR(16)     NOT NULL DEFAULT 'UNKNOWN',
    seniority              VARCHAR(16)     NULL,
    salary_min             DECIMAL(14, 2)  NULL,
    salary_max             DECIMAL(14, 2)  NULL,
    salary_currency        CHAR(3)         NULL,
    salary_period          VARCHAR(8)      NULL,
    salary_min_usd_month   DECIMAL(12, 2)  NULL,
    salary_is_estimated    BOOLEAN         NOT NULL DEFAULT FALSE,
    salary_text            VARCHAR(200)    NULL,
    required_languages     JSON            NULL,
    published_at           DATETIME(6)     NULL,
    published_is_approx    BOOLEAN         NOT NULL DEFAULT FALSE,
    expires_at             DATETIME(6)     NULL,
    canonical_url          VARCHAR(1000)   NULL,
    canonical_url_hash     BINARY(32)      NULL,
    apply_url              VARCHAR(1000)   NULL,
    content_hash           BINARY(32)      NOT NULL,
    fingerprint            BINARY(32)      NOT NULL,
    simhash                BIGINT          NULL,
    status                 VARCHAR(16)     NOT NULL DEFAULT 'ACTIVE',
    duplicate_of_id        BIGINT UNSIGNED NULL,
    first_seen_at          DATETIME(6)     NOT NULL,
    last_seen_at           DATETIME(6)     NOT NULL,
    last_verified_at       DATETIME(6)     NULL,
    created_at             DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at             DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT ck_jo_status CHECK (status IN ('ACTIVE', 'EXPIRED', 'REMOVED', 'DUPLICATE')),
    CONSTRAINT ck_jo_elig CHECK (bolivia_eligibility IN ('ELIGIBLE', 'LIKELY', 'NOT_ELIGIBLE', 'UNKNOWN')),
    INDEX ix_jo_fingerprint (fingerprint),
    INDEX ix_jo_url_hash (canonical_url_hash),
    INDEX ix_jo_status_published (status, published_at),
    INDEX ix_jo_country_status (country, status, published_at),
    INDEX ix_jo_region_modality (region, work_modality, status),
    INDEX ix_jo_eligibility (bolivia_eligibility, status, published_at),
    INDEX ix_jo_salary (salary_min_usd_month),
    INDEX ix_jo_company (normalized_company),
    INDEX ix_jo_first_seen (first_seen_at),
    FULLTEXT INDEX ft_jo_title_desc (title, description_text)
) ENGINE = InnoDB;

CREATE TABLE job_source_references (
    id                BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    job_offer_id      BIGINT UNSIGNED NOT NULL,
    job_source_id     BIGINT UNSIGNED NOT NULL,
    external_id       VARCHAR(200)    NOT NULL,
    source_url        VARCHAR(1000)   NOT NULL,
    apply_url         VARCHAR(1000)   NULL,
    attribution_text  VARCHAR(300)    NULL,
    raw_payload       JSON            NULL,
    raw_content_hash  BINARY(32)      NULL,
    first_seen_at     DATETIME(6)     NOT NULL,
    last_seen_at      DATETIME(6)     NOT NULL,
    removed_at        DATETIME(6)     NULL,
    created_at        DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at        DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    CONSTRAINT uk_jsr_source_ext UNIQUE (job_source_id, external_id),
    CONSTRAINT fk_jsr_offer FOREIGN KEY (job_offer_id) REFERENCES job_offers (id) ON DELETE CASCADE,
    CONSTRAINT fk_jsr_source FOREIGN KEY (job_source_id) REFERENCES job_sources (id),
    INDEX ix_jsr_offer (job_offer_id)
) ENGINE = InnoDB;

CREATE TABLE job_offer_skills (
    job_offer_id  BIGINT UNSIGNED NOT NULL,
    skill_id      BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (job_offer_id, skill_id),
    CONSTRAINT fk_jos_offer FOREIGN KEY (job_offer_id) REFERENCES job_offers (id) ON DELETE CASCADE,
    CONSTRAINT fk_jos_skill FOREIGN KEY (skill_id) REFERENCES skills (id),
    INDEX ix_jos_skill (skill_id, job_offer_id)
) ENGINE = InnoDB;

CREATE TABLE user_job_states (
    user_id       BIGINT UNSIGNED NOT NULL,
    job_offer_id  BIGINT UNSIGNED NOT NULL,
    saved         BOOLEAN         NOT NULL DEFAULT FALSE,
    hidden        BOOLEAN         NOT NULL DEFAULT FALSE,
    seen_at       DATETIME(6)     NULL,
    updated_at    DATETIME(6)     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (user_id, job_offer_id),
    CONSTRAINT fk_ujs_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_ujs_offer FOREIGN KEY (job_offer_id) REFERENCES job_offers (id) ON DELETE CASCADE,
    INDEX ix_ujs_saved (user_id, saved)
) ENGINE = InnoDB;

-- Exchange rates entered by the admin (no external FX API). Used only to normalize salaries for filtering.
CREATE TABLE fx_rates (
    currency     CHAR(3)        NOT NULL,
    rate_to_usd  DECIMAL(18, 8) NOT NULL,
    as_of        DATE           NOT NULL,
    PRIMARY KEY (currency, as_of)
) ENGINE = InnoDB;
